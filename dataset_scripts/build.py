def main():
    parser = argparse.ArgumentParser(description="Speech/music dataset builder")
    tier_group = parser.add_mutually_exclusive_group()
    tier_group.add_argument("--tier", choices=list(TIERS), default="mid",
                            help="Preset tier: mini=1h, mid=20h, full=200h  (default: mid)")
    tier_group.add_argument("--hours", type=float,
                            help="Custom total hours (overrides --tier)")
    parser.add_argument("--skip-aug", action="store_true",
                        help="Skip augmentation step (run augment_over_music.py separately)")
    parser.add_argument("--out-dir", type=Path,
                        help="Override output directory")
    args = parser.parse_args()

    total_hours = args.hours if args.hours is not None else TIERS[args.tier]
    tier_name   = args.tier if args.hours is None else "custom"
    data_dir    = args.out_dir or TIER_DIRS.get(tier_name, Path("data"))

    specs = make_specs(total_hours)

    print("=" * 60)
    print(f"Dataset build  [{tier_name}]  {total_hours:.1f}h total")
    print(f"Output  : {data_dir.resolve()}")
    print(f"Sources : {len(specs)}")
    print(f"Speech  : {total_hours * 0.45:.1f}h   "
          f"Music: {total_hours * 0.45:.1f}h   "
          f"Noise: {total_hours * 0.10:.1f}h")
    print("=" * 60)

    failed, succeeded = [], []
    for spec in specs:
        ok = process_source(spec, data_dir)
        (succeeded if ok else failed).append(spec.name)

    print("\n" + "=" * 60)
    print(f"Base sources: {len(succeeded)} OK, {len(failed)} FAILED")
    if failed:
        for name in failed:
            print(f"  ✗ {name}")

    if not args.skip_aug:
        print("\nRunning augmentation...")
        from augment_over_music import run_augmentation
        run_augmentation(total_hours=total_hours, data_dir=data_dir)

    print("\nBuild complete.")
    print("=" * 60)


if __name__ == "__main__":
    main()
