# ─────────────────────────────────────────────────────────────────────────────
# Labelers
# ─────────────────────────────────────────────────────────────────────────────


def _ms(samples: int) -> int:
    return int(samples * 1000 / SR)


def make_label(label: str, start: int, end: int) -> dict:
    return {"label": label, "start": start, "end": end}


class VADLabeler:
    def __init__(self):
        self.model = load_silero_vad()

    def label(self, audio: AudioDecoder, _thr: int) -> list[dict] | None:
        try:
            samples = audio.get_all_samples()
        except RuntimeError:
            return None

        n = samples.data.shape[-1]
        timestamps = get_speech_timestamps(samples.data, self.model)

        if not timestamps:
            return [make_label("inactive", 0, _ms(n))]

        labels, prev_end = [], 0
        for ts in timestamps:
            if ts["start"] > prev_end:
                labels.append(make_label("inactive", _ms(prev_end), _ms(ts["start"])))
            labels.append(make_label("speech", _ms(ts["start"]), _ms(ts["end"])))
            prev_end = ts["end"]
        if prev_end < n:
            labels.append(make_label("inactive", _ms(prev_end), _ms(n)))
        return labels


class MusicLabeler:
    def label(self, audio: dict, silence_threshold: int) -> list[dict] | None:
        seg = (
            AudioSegment.from_file(io.BytesIO(audio["bytes"]))
            if audio["bytes"] is not None
            else AudioSegment.from_file(audio["path"])
        )
        silent_ranges = silence.detect_silence(seg, min_silence_len=260, silence_thresh=silence_threshold)

        if not silent_ranges:
            return [make_label("music", 0, len(seg))]

        labels, prev_end = [], 0
        for s, e in silent_ranges:
            if s > prev_end:
                labels.append(make_label("music", prev_end, s))
            labels.append(make_label("inactive", s, e))
            prev_end = e
        if prev_end < len(seg):
            labels.append(make_label("music", prev_end, len(seg)))
        return labels


class SilenceLabeler:
    def label(self, audio: AudioDecoder | dict, _thr: int) -> list[dict]:
        if isinstance(audio, AudioDecoder):
            dur_ms = int(audio.get_all_samples().duration_seconds * 1000)
        else:
            seg = (
                AudioSegment.from_file(io.BytesIO(audio["bytes"]))
                if audio["bytes"] is not None
                else AudioSegment.from_file(audio["path"])
            )
            dur_ms = len(seg)
        return [make_label("inactive", 0, dur_ms)]


_LABELER_CACHE: dict = {}


def get_labeler(detector: str) -> VADLabeler | MusicLabeler | SilenceLabeler:
    if detector not in _LABELER_CACHE:
        match detector:
            case "vad":      _LABELER_CACHE["vad"]     = VADLabeler()
            case "music":    _LABELER_CACHE["music"]   = MusicLabeler()
            case "silence":  _LABELER_CACHE["silence"] = SilenceLabeler()
            case _:          raise ValueError(f"Unknown detector: {detector!r}")
    return _LABELER_CACHE[detector]


# ─────────────────────────────────────────────────────────────────────────────
# SplitWriter
# ─────────────────────────────────────────────────────────────────────────────


class SplitWriter:
    def __init__(self, split: str, data_dir: Path):
        self.base = data_dir / split
        self.base.mkdir(parents=True, exist_ok=True)
        self._resume()

    def _resume(self):
        existing = sorted(
            [d for d in self.base.iterdir() if d.is_dir() and d.name.isdigit()],
            key=lambda d: int(d.name),
        )
        if not existing:
            self.folder_idx = 0
            self.folder = self.base / "000"
            self.folder.mkdir()
            self.file_count = 0
        else:
            self.folder = existing[-1]
            self.folder_idx = int(self.folder.name)
            self.file_count = len(list(self.folder.glob("*.wav")))

    def _rotate_if_full(self):
        if self.file_count >= MAX_FILES_PER_FOLDER:
            self.folder_idx += 1
            self.folder = self.base / f"{self.folder_idx:03d}"
            self.folder.mkdir(exist_ok=True)
            self.file_count = 0

    def write(self, audio: AudioDecoder | dict, labels: list[dict],
              name: str, idx: int, cls: str, subclass: str):
        self._rotate_if_full()
        file_name = f"{name}_{idx:05d}.wav"
        file_path = self.folder / file_name
        if file_path.exists():
            return

        if isinstance(audio, AudioDecoder):
            data = audio.get_all_samples().data
            if hasattr(data, "cpu"):
                data = data.cpu()
            sf.write(file_path, data.numpy().squeeze(), samplerate=SR)
        else:
            seg = (
                AudioSegment.from_file(io.BytesIO(audio["bytes"]))
                if audio["bytes"] is not None
                else AudioSegment.from_file(audio["path"])
            )
            seg.export(file_path, format="wav")

        with jsonlines.open(self.folder / "metadata.jsonl", mode="a") as f:
            f.write({"file_name": file_name, "class": cls, "subclass": subclass, "labels": labels})
        self.file_count += 1


