"""
Dataset builder — parametric by total hours (80/10/10 train/val/test)
======================================================================

Tiers:
    mini   1h   (smoke-test / fast iteration)
    mid   20h   (default, training-ready)
    full 200h   (large-scale)

Run:
    uv run python build.py --tier mid          # 20h to data/
    uv run python build.py --tier mini         # 1h  to data_mini/
    uv run python build.py --tier full         # 200h to data_full/
    uv run python build.py --hours 50          # custom to data/

Class split (all tiers):
    Speech  45%
    Music   45%
    Noise   10%

Speech sub-classes (% of speech total):
    clean 40% | corrupted 20% | noisy 20% | multispeaker 7.5%
    speech+music 7.5% | MS+music 5%   ← generated by augment_over_music.py

Music sub-classes (equal 1/9 share each):
    electronic | folk | hip-hop | instrumental | pop | rock  →  rpmon/fma-genre-classification
    jazz       →  PlutoG99001/MusicGen-Jazz-Clean
    country    →  ylacombe/music_genres_Country
    vocal      →  ccmusic-database/acapella  (song1/song2/song3, 1/3 each)

Noise:
    AxonData/background-noise-detection-dataset  (70%)
    danavery/urbansound8K                        (30%)

Streaming stops per-source when accumulated duration reaches target_seconds.
Train/val/test split is by accumulated duration (0–80% / 80–90% / 90–100%).
"""

