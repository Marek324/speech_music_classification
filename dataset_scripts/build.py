def load_source(spec: DatasetSpec) -> IterableDataset:
    ds = load_dataset(spec.hf_id, split=spec.split, streaming=True, **spec.extra_load_kwargs)
    assert isinstance(ds, IterableDataset)
    ds = ds.shuffle(seed=RAND_SEED)
    if spec.filter_col and spec.filter_val is not None:
        ds = ds.filter(lambda row: row[spec.filter_col] == spec.filter_val)
    if spec.skip > 0:
        ds = ds.skip(spec.skip)
    ds = ds.take(spec.max_rows)
    ds = ds.select_columns(spec.audio_col)
    ds = ds.cast_column(spec.audio_col, Audio(sampling_rate=SR, num_channels=1, decode=spec.audio_decode))
    return ds


def process_source(spec: DatasetSpec, data_dir: Path) -> bool:
    """
    Stream source until target_seconds accumulated; assign rows to
    train/val/test by duration proportion (80/10/10).
    Returns True if at least one row was written.
    """
    print(f"\n{'─' * 60}")
    print(f"  {spec.name}  [{spec.cls} → {spec.subclass}]")
    print(f"  target: {spec.target_seconds / 3600:.3f}h  ({spec.target_seconds:.0f}s)")
    print(f"{'─' * 60}")

    try:
        ds = load_source(spec)
    except Exception as e:
        print(f"  [FAIL] load_source: {e}", file=sys.stderr)
        return False

    labeler = get_labeler(spec.detector)
    writers = {s: SplitWriter(s, data_dir) for s in ("train", "val", "test")}

    train_cutoff = spec.target_seconds * 0.8
    val_cutoff   = spec.target_seconds * 0.9
    accumulated  = 0.0
    local_idx    = 0
    any_written  = False

    for row in tqdm(ds, desc=f"  {spec.name}"):
        labels = labeler.label(row[spec.audio_col], spec.sil_thr)
        if labels is None:
            print(f"  [SKIP] row {local_idx} — invalid audio", file=sys.stderr)
            local_idx += 1
            continue

        clip_s = labels[-1]["end"] / 1000.0

        if accumulated < train_cutoff:
            split_name = "train"
        elif accumulated < val_cutoff:
            split_name = "val"
        else:
            split_name = "test"

        writers[split_name].write(row[spec.audio_col], labels, spec.name, local_idx, spec.cls, spec.subclass)
        accumulated += clip_s
        local_idx += 1
        any_written = True

        if accumulated >= spec.target_seconds:
            break

    pct = accumulated / spec.target_seconds * 100 if spec.target_seconds else 0
    print(f"  {accumulated / 60:.1f} min written  (target {spec.target_seconds / 60:.1f} min, {pct:.0f}%)")
    if pct < 90:
        print(f"  [WARN] source exhausted before reaching target", file=sys.stderr)
    return any_written


