def make_entries(tier: TierName) -> list[SourceEntry]:
    entries = SOURCES[tier].entries
    total_min = sum(e.target_minutes for e in entries)
    if total_min <= 0:
        raise ValueError(f"Tier {tier!r} has zero total target_minutes")
    return list(entries)


def _tier_total_minutes(tier: TierName) -> float:
    return float(sum(e.target_minutes for e in SOURCES[tier].entries))


TIER_TOTAL_MINUTES: dict[TierName, float] = {t: _tier_total_minutes(t) for t in TierName}
